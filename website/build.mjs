/** A CSS font-family list: names with spaces are quoted, generic keywords and ui-* are not. */
const fontStack = (names) => names.map((n) => (/\s/.test(n) ? `"${n}"` : n)).join(", ");

/**
 * The `:root` block of --brand-* custom properties, prepended to styles.css so
 * the colours, radii and font stacks exist in exactly one place. styles.css maps
 * its own short names (--bg, --accent, ...) onto these.
 */
function brandCss() {
  const vars = {
    ...Object.fromEntries(Object.entries(BRAND.violet).map(([step, v]) => [`violet-${step}`, v])),
    "ink-950": BRAND.ink["950"],
    "ink-900": BRAND.ink["900"],
    plate: BRAND.ink.plate,
    text: BRAND.text.default,
    "text-muted": BRAND.text.muted,
    "text-subtle": BRAND.text.subtle,
    success: BRAND.status.success,
    warning: BRAND.status.warning,
    danger: BRAND.status.danger,
    ...Object.fromEntries(Object.entries(BRAND.radius).map(([size, px]) => [`radius-${size}`, `${px}px`])),
    "font-sans": fontStack(BRAND.font.sans),
    "font-mono": fontStack(BRAND.font.mono),
  };
  const lines = Object.entries(vars).map(([name, value]) => `  --brand-${name}: ${value};`);
  return `/* Generated by website/build.mjs from brand/tokens.json. Do not edit. */\n:root {\n${lines.join("\n")}\n}\n\n`;
}

/** Copy a file the site cannot work without; a missing one is a broken setup, not something to skip. */
function copyRequired(src, dest, hint) {
  if (!existsSync(src)) throw new Error(`Missing required file: ${relative(ROOT, src)} (${hint})`);
  copyFileSync(src, dest);
}

