#!/usr/bin/env bash
# Regenerate docs/internals/modules.md from the `//!` header of every src/*.rs.
#
# WHY GENERATED: a hand-synced module table goes stale, and a stale map is worse than
# no map — agents obey docs over their own reading. The module headers are the single
# source of truth; this script only transcribes them, and fails loudly when one is
# missing so the fix happens in the code rather than in the table.
set -euo pipefail
cd "$(dirname "$0")/../.."

OUT="${1:-docs/internals/modules.md}"
missing=0

{
  echo "# Module index"
  echo
  echo "Generated by \`scripts/docs/codemap.sh\` from the \`//!\` header of each file."
  echo "Do not hand-edit: change the module header instead, then re-run the script."
  echo "It is generated so the index cannot drift from the code: the module headers are the single source of truth."
  echo
  echo "Last verified: $(date +%Y-%m-%d)"
  echo
  echo "| module | lines | purpose |"
  echo "|---|---|---|"
} > "$OUT"

# Every module file, nested submodules included (`collab/relay.rs`), in path
# order so a submodule sorts directly after its parent. Test-only files are
# not modules with a job of their own and stay out of the index.
files="$(find src -name '*.rs' ! -name '*tests.rs' ! -path '*/tests/*' | sed 's#^src/##' | LC_ALL=C sort | sed 's#^#src/#')"
for f in $files; do
  name="${f#src/}"
  lines="$(wc -l < "$f" | tr -d ' ')"
  # First contiguous //! block, joined to one sentence-ish line: the header's first
  # line is the summary by convention, so take it and stop.
  # Join the contiguous //! block into one line, then cut at the first sentence
  # end: a header's first LINE is often a wrapped fragment, and a truncated purpose
  # ("`public/` is compiled into the") is worse than none.
  purpose="$(awk '/^\/\/!/{sub(/^\/\/![ ]?/,"");printf "%s ",$0;next}{if(NR>1)exit}' "$f" \
    | sed 's/  */ /g; s/^ //' \
    | awk -F'\\. ' '{printf "%s", $1}' \
    | sed 's/[[:space:]]*$//; s/\.*$/./' \
    | cut -c1-200)"
  if [ -z "$purpose" ]; then
    echo "MISSING //! header: $f" >&2
    missing=$((missing + 1))
    purpose="(no //! header — add one)"
  fi
  # Escape pipes so a header containing one cannot break the table.
  purpose="${purpose//|/\\|}"
  printf '| `%s` | %s | %s |\n' "$name" "$lines" "$purpose" >> "$OUT"
done

{
  echo
  echo "Totals: $(echo "$files" | wc -l | tr -d ' ') module files, $(cat $files | wc -l | tr -d ' ') lines (test-only files excluded)."
  echo
  echo "A module that outgrew one file is a directory: \`x.rs\` keeps the module's header,"
  echo "its public API and the types its parts share, and \`x/<part>.rs\` holds one cohesive"
  echo "section each (\`http/socket.rs\`, \`child/spawn.rs\`). Its unit tests sit beside the"
  echo "code they test, or in \`x/tests.rs\` with topic suites under \`x/tests/\`."
} >> "$OUT"

echo "wrote $OUT"
if [ "$missing" -ne 0 ]; then
  echo "$missing module(s) lack a //! header — add them, then re-run" >&2
  exit 1
fi
